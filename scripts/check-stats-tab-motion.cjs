const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.connectOverCDP('http://127.0.0.1:9333');
  let page=null;
  for(const context of browser.contexts()) for(const item of context.pages()) if(!page&&!item.url().startsWith('devtools')) page=item;
  assert(page,'no page');
  await page.waitForTimeout(2000);
  await page.evaluate(()=>{document.querySelector('[data-nav="stats"]')?.click();});
  await page.waitForTimeout(1200);
  const probe=await page.evaluate(()=>{window.__motionSamples=[];const view=document.querySelector('#view');let running=true;(function sample(){if(!running)return;window.__motionSamples.push({t:performance.now(),viewAnimations:view.getAnimations().map(a=>({state:a.playState,opacity:a.effect?.getKeyframes()?.[0]?.opacity})),thumb:(()=>{const t=document.querySelector('#page-subnav .subnav-highlight');return t?{transform:t.style.transform,height:t.style.height}:null;})()});requestAnimationFrame(sample);})();return true;});
  assert.ok(probe);
  const rows=await page.evaluate(()=>[...document.querySelectorAll('#page-subnav [data-subnav]')].map(b=>{const r=b.getBoundingClientRect();return {key:b.dataset.subnav,x:r.x+r.width/2,y:r.y+r.height/2};}));
  assert.ok(rows.length>=4,'stats subnav missing: '+JSON.stringify(rows));
  const target=rows.find(r=>r.key==='tokens');
  await page.mouse.move(target.x,target.y);
  await page.mouse.down();
  await page.mouse.up();
  await page.waitForTimeout(700);
  const samples=await page.evaluate(()=>{const s=window.__motionSamples;return {count:s.length,viewFrames:s.map(x=>x.viewAnimations.length).filter(n=>n>0).length,thumbFrames:s.map(x=>x.thumb&&x.thumb.transform).filter(Boolean).slice(0,3),lastThumb:s[s.length-1]?.thumb};});
  await page.evaluate(()=>{window.__motionSamples=[];});
  const target2=rows.find(r=>r.key==='recent');
  await page.mouse.move(target2.x,target2.y);
  await page.mouse.down();
  await page.mouse.up();
  await page.waitForTimeout(700);
  const samples2=await page.evaluate(()=>{const s=window.__motionSamples;return {viewFrames:s.map(x=>x.viewAnimations.length).filter(n=>n>0).length,thumbFrames:s.map(x=>x.thumb&&x.thumb.transform).filter(Boolean).slice(0,3)};});
  console.log(JSON.stringify({first:samples,second:samples2},null,2));
  await browser.close();
})().catch(e=>{console.error('FAIL',e.message);process.exit(1);});
